#!/bin/sh
# Creates deploy/compose/kitmaker.env from the example on first run, then
# makes sure it has the values that must be unique per machine: the secrets
# keeper key and the bootstrap admin password. Safe to run repeatedly.
set -eu
dir=$(dirname "$0")
env="$dir/kitmaker.env"

if [ ! -f "$env" ]; then
	cp "$dir/kitmaker.env.example" "$env"
	echo "Created $env (edit it, then: make restart)"
fi

if ! grep -q '^KITMAKER_SECRETS_URL=' "$env"; then
	key=$(openssl rand -base64 32 | tr '+/' '-_')
	printf '\n# Generated by deploy/compose/env.sh: local secrets keeper key. Losing it makes\n# stored integration secrets unreadable.\nKITMAKER_SECRETS_URL=base64key://%s\n' "$key" >>"$env"
	echo "Added KITMAKER_SECRETS_URL to $env"
fi

if ! grep -q '^KITMAKER_BOOTSTRAP_PASSWORD=' "$env"; then
	pw=$(openssl rand -base64 18 | tr -d '/+=')
	printf '\n# Generated by deploy/compose/env.sh: first sign-in password for KITMAKER_BOOTSTRAP_ADMIN.\n# Only used when that account has no password yet.\nKITMAKER_BOOTSTRAP_PASSWORD=%s\n' "$pw" >>"$env"
	echo "Added KITMAKER_BOOTSTRAP_PASSWORD to $env"
fi
